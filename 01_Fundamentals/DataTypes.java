/*
There are 8 data types predefined in Java, known as primitive data types.

*/

class DataTypes {
    public static void main(String[] args) {
        // 1. boolean type
        boolean flag = true;
        System.out.println(flag); // prints true

        // 2. byte type
        byte range;
        range = 124;
        System.out.println(range); // prints 124

        // 3. short type
        short temperature;
        temperature = -200;
        System.out.println(temperature); // prints -200

        // 4. int type
        int range1 = -4250000;
        System.out.println(range1); // print -4250000

        // 5. long type
        long range2 = -42332200000L;
        System.out.println(range2); // prints -42332200000

        // 6. float type
        float number = -42.3f;
        System.out.println(number); // prints -42.3

        // 7. double type
        double number1 = -42.3d;
        System.out.println(number1); // prints -42.3

        // 8. char type
        char letter = 'A';
        System.out.println(letter); // prints A

        // 9. String type (objects, not a primitive data type)
        String name = "Hello World";
        System.out.println(name); // prints Hello World
    }
}